using System.Globalization;
using System.Text;
using Daignostic.Core.Ai;
using Daignostic.Core.Analysis;

namespace Daignostic.Core.Reporting;

/// <summary>Builds a shareable Markdown report. Contains no file paths, device names or credentials.</summary>
public static class MarkdownReport
{
    public static string Build(AnalysisResult r, AiAnalysis? ai)
    {
        var sb = new StringBuilder();
        var inv = CultureInfo.InvariantCulture;
        sb.AppendLine($"# {Or(r.Info.Game, "Capture")} - performance report");
        sb.AppendLine();
        sb.AppendLine($"- GPU: {Or(r.Info.Gpu, "n/a")} (driver {Or(r.Info.GpuDriver, "n/a")})");
        sb.AppendLine($"- CPU: {Or(r.Info.Cpu, "n/a")}");
        sb.AppendLine($"- Resolution: {Or(r.Info.Resolution, "n/a")}, API: {Or(r.Info.GraphicsApi, "n/a")}");
        sb.AppendLine($"- Duration: {r.Metrics.DurationSec.ToString("0", inv)} s");
        sb.AppendLine();

        sb.AppendLine("## Frame rate");
        sb.AppendLine();
        sb.AppendLine("| Metric | Value |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| Average | {r.Metrics.AverageFps.ToString("0.0", inv)} fps |");
        sb.AppendLine($"| 1% (P1) | {r.Metrics.P1Fps.ToString("0.0", inv)} fps |");
        sb.AppendLine($"| 1% low average | {r.Metrics.Low1AverageFps.ToString("0.0", inv)} fps |");
        sb.AppendLine($"| 0.1% low average | {r.Metrics.Low01AverageFps.ToString("0.0", inv)} fps |");
        sb.AppendLine($"| Stutters | {r.Stutters.Count} |");
        sb.AppendLine($"| Freezes (200 ms or more) | {r.Freezes.Count} |");
        sb.AppendLine($"| Bottleneck | {r.Bottleneck.Verdict} ({r.Bottleneck.Confidence}) |");
        sb.AppendLine();

        sb.AppendLine("## Findings");
        sb.AppendLine();
        foreach (var f in r.Findings)
        {
            sb.AppendLine($"- **[{f.Severity}] {f.Title}.** {f.Detail}");
        }

        sb.AppendLine();
        if (r.Settings is { } settings)
        {
            sb.AppendLine($"## Game settings ({settings.GameName})");
            sb.AppendLine();
            sb.AppendLine("Read from the game's config file at its last save; may differ from what was active during the capture.");
            sb.AppendLine();
            foreach (var item in settings.Items)
            {
                sb.AppendLine($"- {item.Label}: {item.Value}");
            }

            sb.AppendLine();
        }

        if (ai is not null)
        {
            sb.AppendLine("## AI analysis");
            sb.AppendLine();
            sb.AppendLine("_Written by a language model from the measured facts above. Treat it as a suggestion, not a verdict._");
            sb.AppendLine();
            if (!string.IsNullOrWhiteSpace(ai.Summary))
            {
                sb.AppendLine(ai.Summary);
                sb.AppendLine();
            }

            foreach (var item in ai.Items)
            {
                sb.AppendLine($"### {item.Title} ({Or(item.Confidence, "unrated")} confidence)");
                sb.AppendLine();
                sb.AppendLine(item.Explanation);
                foreach (var action in item.Actions)
                {
                    sb.AppendLine($"- Try: {action}");
                }

                sb.AppendLine();
                sb.AppendLine($"Evidence: {string.Join(", ", item.Evidence)}");
                sb.AppendLine();
            }

            if (ai.Inconclusive)
            {
                sb.AppendLine("The AI marked its analysis as inconclusive.");
                sb.AppendLine();
            }
        }

        sb.AppendLine("---");
        sb.AppendLine("Generated by daignostic.");
        return sb.ToString();
    }

    private static string Or(string value, string fallback) => string.IsNullOrWhiteSpace(value) ? fallback : value;
}

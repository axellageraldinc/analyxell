using System.Globalization;
using System.Text;
using Daignostic.Core.Analysis;

namespace Daignostic.Core.Ai;

/// <summary>
/// Builds a single Markdown file a person can give to any AI they like (a chat window, a local model) instead of
/// configuring one inside daignostic. It contains the same measured facts the built-in AI would receive, plus
/// instructions, and nothing else: no file paths, device name or credentials.
/// </summary>
public static class AiExportPack
{
    public const string ConversationalSystem = """
        You are a PC game performance diagnostician. Below is JSON produced by software that already measured a gameplay capture.
        Rules:
        1. Use ONLY the facts and findings in the data. Never invent numbers, settings, hardware or causes.
        2. Cite the data key in square brackets after each claim, for example [fps.p1] or [finding:FREEZES].
        3. Separate what was measured from what is only a hypothesis. Never present a hypothesis as proven.
        4. If the data cannot support a conclusion, say so plainly.
        5. Each finding carries "suggestions" written by the app. Build on them: put the most valuable first, explain why for THIS data, and drop ones that clearly do not apply. Add your own only if it is an in-game setting or a simple, reversible check. Never suggest commands, registry edits, BIOS changes, downloads or deleting files.
        6. Suggest one change at a time, and say how to check the result: record again and compare.
        7. Answer once, completely. Do NOT ask the user questions and do not end by asking for more information. If something is missing, say what you assumed, give guidance that holds either way ("if X, then Y; otherwise Z"), and list it under "What I could not tell".
        Answer in short sections: "What I see", "Most likely causes" (label each as measured or hypothesis), "What to try first" (numbered), "How to check it worked", "What I could not tell" (only if something is missing). Plain language, concise.
        """;

    public static string BuildSingle(AnalysisResult result, string? userNote, DateTime generatedAtUtc) =>
        Assemble(result.Info.Game, AiPrompts.BuildSingle(result, userNote), userNote, generatedAtUtc, "one capture");

    public static string BuildComparison(ComparisonResult comparison, AnalysisResult a, AnalysisResult b, string? userNote, DateTime generatedAtUtc) =>
        Assemble(b.Info.Game, AiPrompts.BuildComparison(comparison, a, b, userNote), userNote, generatedAtUtc, "a comparison of two runs");

    private static string Assemble(string game, string dataJson, string? note, DateTime generatedAtUtc, string kind)
    {
        var sb = new StringBuilder();
        var title = string.IsNullOrWhiteSpace(game) ? "game capture" : game;
        sb.AppendLine($"# daignostic analysis pack: {title}");
        sb.AppendLine();
        sb.AppendLine($"_Generated by daignostic on {generatedAtUtc.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)} ({kind}). It holds measurements only. It does not contain file paths, your computer's name, account details or any API key._");
        sb.AppendLine();
        sb.AppendLine("## How to use this file");
        sb.AppendLine();
        sb.AppendLine("1. Open the AI you like (a chat website, an app, or a local model).");
        sb.AppendLine("2. Attach this file, or paste the whole text as your first message.");
        sb.AppendLine("3. Send it. Ask follow-up questions if you want; the AI should keep to the data below.");
        sb.AppendLine();
        sb.AppendLine("## Instructions for the AI");
        sb.AppendLine();
        sb.AppendLine(ConversationalSystem);
        sb.AppendLine();
        sb.AppendLine("## The data");
        sb.AppendLine();
        sb.AppendLine("```json");
        sb.AppendLine(dataJson);
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("## What I would like to know");
        sb.AppendLine();
        sb.AppendLine(string.IsNullOrWhiteSpace(note)
            ? "What is wrong with how this game ran, what is most likely causing it, and what should I try first?"
            : note.Trim());
        sb.AppendLine();
        sb.AppendLine("## Checking the answer");
        sb.AppendLine();
        sb.AppendLine("- Every claim should point to a key in the data. If one does not, ask: \"Which value in the data supports that?\"");
        sb.AppendLine("- Treat anything marked as a hypothesis as something to test, not a fact.");
        sb.AppendLine("- Change one thing, record the same route again, and use Compare in daignostic to see whether it helped.");
        return sb.ToString();
    }
}
